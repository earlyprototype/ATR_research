"""EXP_017: render every results table mechanically from the committed JSON.

RESULTS_EXP010B.md carries a dated erratum recording five numbers that were
hand-copied into a results record and matched no committed artifact. This
script exists so that no number in RESULTS_EXP017.md is hand-copied: it reads
output/exp017_partition.json and output/exp017_jspace.json and writes
output/tables.md, and the results record quotes those tables.

Usage: python3 make_tables.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "output"


def fmt(x, nd=4):
    if x is None:
        return "not applicable"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def main():
    lines = ["# EXP_017 tables, generated from the committed JSON artifacts",
             "",
             "Generated by `make_tables.py`; do not edit by hand.", ""]
    p = json.load(open(OUT / "exp017_partition.json"))

    # ---- per-prompt terminal table -----------------------------------------
    lines += ["## Per-prompt terminal table", "",
              "| prompt | category | base terminal | base lock | twin terminal | "
              "twin lock | base loudness | twin loudness |",
              "|---|---|---|---|---|---|---|---|"]
    for r in p["per_prompt"]:
        lines.append(
            f"| {r['prompt_id']} | {r['category']} | `{r['base_terminal']}` "
            f"(p {r['base_prob']:.3f}) | {r['base_lock_in_iter'] if r['base_converged'] else 'never'} "
            f"| `{r['twin_terminal']}` (p {r['twin_prob']:.3f}) "
            f"| {r['twin_lock_in_iter'] if r['twin_converged'] else 'never'} "
            f"| {r['base_loudness_ratio']:.1f}x | {r['twin_loudness_ratio']:.1f}x |")
    lines.append("")

    # ---- summaries ----------------------------------------------------------
    lines += ["## Run summary", "",
              "| quantity | base GPT-2 Small | the twin |", "|---|---|---|"]
    b, t = p["base_summary"], p["twin_summary"]
    rows = [("prompts that settled, of 25", b["converged"], t["converged"]),
            ("settling iterations seen", b["lock_in_iters"], t["lock_in_iters"]),
            ("distinct terminal readout tokens", len(b["terminal_tokens"]),
             len(t["terminal_tokens"])),
            ("mean readout probability of the top token",
             fmt(b["mean_terminal_prob"]), fmt(t["mean_terminal_prob"])),
            ("entry loudness ratio, mean",
             f"{b['loudness_ratio_mean']}x", f"{t['loudness_ratio_mean']}x"),
            ("entry loudness ratio, range",
             f"{b['loudness_ratio_range'][0]}x to {b['loudness_ratio_range'][1]}x",
             f"{t['loudness_ratio_range'][0]}x to {t['loudness_ratio_range'][1]}x"),
            ("used the twin's extra vocabulary entry",
             fmt(b["extra_vocab_token_used"]), fmt(t["extra_vocab_token_used"]))]
    for name, bb, tt in rows:
        lines.append(f"| {name} | {bb} | {tt} |")
    lines += ["", "Terminal readout tokens and their counts:", "",
              f"- base GPT-2 Small: {b['terminal_tokens']}",
              f"- the twin: {t['terminal_tokens']}", ""]
    if b.get("lag_scan_mean") and t.get("lag_scan_mean"):
        lines += ["Mean similarity between iterations k apart over the 25 prompts, "
                  "on a cosine scale from -1 to 1 where 1 means identical direction:",
                  "", "| lag k | base | twin |", "|---|---|---|"]
        for k in sorted(b["lag_scan_mean"], key=int):
            lines.append(f"| {k} | {b['lag_scan_mean'][k]:.4f} | "
                         f"{t['lag_scan_mean'][k]:.4f} |")
        lines.append("")

    # ---- H18 ----------------------------------------------------------------
    pr = p["h18_primary"]
    lines += ["## H18: the partition comparison", "",
              f"- Groups at the registered threshold 0.999: base {pr['base_basins']}, "
              f"twin {pr['twin_basins']}, over 25 prompts.",
              f"- Verdict: **{pr['h18']}**."]
    for k in ("ari", "perm_p", "ari_if_forced", "perm_p_if_forced"):
        if k in pr:
            lines.append(f"- {k}: {pr[k]}")
    if "reason" in pr:
        lines.append(f"- Reason: {pr['reason']}")
    lines += ["", "Threshold sweep, descriptive only:", "",
              "| threshold | base groups | twin groups | adjusted Rand index | permutation p |",
              "|---|---|---|---|---|"]
    for r in p["h18_threshold_sweep"]:
        lines.append(f"| {r['threshold']} | {r['base_basins']} | {r['twin_basins']} "
                     f"| {fmt(r.get('ari'))} | {fmt(r.get('perm_p'), 5)} |")
    lines.append("")
    s1 = p["h18_secondary_committed_lag1"]
    lines += ["Secondary readings, no verdict weight:", "",
              f"- Against the committed lag-1 arm SB terminals ({s1['base_lag1_basins']} "
              f"groups): " + ", ".join(f"{k} {v}" for k, v in s1.items()
                                       if k.startswith(("ari", "perm"))) + ".",
              f"- {s1.get('note', 'no guard note')}."]
    s2 = p["h18_secondary_exp010d"]
    if "ari_exp010d_vs_twin" in s2:
        lines.append(f"- Against EXP_010d's committed Small reference on the "
                     f"{s2['n_shared_prompts']} shared prompts: twin "
                     f"{s2['ari_exp010d_vs_twin']} (p {s2['perm_p']}), this run's base "
                     f"{s2['ari_exp010d_vs_this_runs_base']} (p {s2['perm_p_base']}); "
                     f"group counts EXP_010d {s2['exp010d_basins']}, twin "
                     f"{s2['twin_basins']}, base {s2['base_basins']}.")
    lines.append("")

    # ---- H18a ---------------------------------------------------------------
    h = p["h18a"]
    a, bb = h["reading_a_verdict_bearing"], h["reading_b_secondary"]
    lines += ["## H18a: the readout tokens", "",
              f"- Threshold: {h['threshold']}.",
              f"- Reading A, verdict-bearing ({a['set_source']}): **{a['hits']} of 25**, "
              f"verdict **{a['h18a']}**. Token set: {a['token_set']}.",
              f"- Reading B, secondary ({bb['set_source']}): {bb['hits']} of 25, "
              f"which {bb['reading']}. Token set: {bb['token_set']}.",
              f"- The twin's most repeated terminal token is "
              f"`{h['twin_repeated_terminal']['token']}` on "
              f"{h['twin_repeated_terminal']['count']} of 25 prompts.",
              f"- Prompts where the twin's top token equals base's top token: "
              f"{h['twin_top1_equals_base_top1_same_prompt']} of 25.",
              f"- Prompts where a Stage 1 basin token appears anywhere in the twin's "
              f"top five: {h['twin_top5_contains_a_stage1_basin_token']} of 25.", ""]

    # ---- H18b ---------------------------------------------------------------
    jp = OUT / "exp017_jspace.json"
    j = json.load(open(jp)) if jp.exists() else None
    # The four combinations of whose states and whose lens, in the order the
    # record's control tables use them. Defined here rather than inside the
    # registered section, because the Hugging Face frame section below renders
    # the same table and must not depend on the registered artifact existing.
    adjusted_all = [("base-on-base", "base states, base lens"),
                    ("twin-on-twin", "twin states, twin lens"),
                    ("twin-on-base", "twin states, base lens"),
                    ("base-on-twin", "base states, twin lens")]
    if j is not None:
        hb = j["h18b"]
        lines += ["## H18b: the J-space share", "",
                  f"- Verdict: **{hb['h18b']}** "
                  f"({hb['n_band_layers_meeting_both']} of the 6 band layers meet both "
                  f"conditions: {hb['band_layers_meeting_both']}).", "",
                  "| layer | twin median share | base median share | absolute difference "
                  "| control spread | permutation p | both conditions | band |",
                  "|---|---|---|---|---|---|---|---|"]
        for l in j["probe_layers"]:
            r = hb["per_layer"][str(l)]
            lines.append(
                f"| {l} | {r['median_twin']:.4f} | {r['median_base']:.4f} "
                f"| {r['abs_median_difference']:.4f} | {r['control_spread']:.4f} "
                f"| {r['perm_p']} | {fmt(r['both_conditions'])} "
                f"| {'yes' if r['in_band'] else 'no'} |")
        lines += ["", "### Cross-checks and controls", "",
                  "Median share over the 25 prompts, with the three rotation controls "
                  "in brackets. A row's four numbers are the real dictionary and then "
                  "the same dictionary randomly rotated with seeds 2026, 2027 and 2028.",
                  "", "| layer | " + " | ".join(sorted(j["cross_checks"])) + " |",
                  "|---" * (1 + len(j["cross_checks"])) + "|"]
        for l in j["probe_layers"]:
            cells = []
            for key in sorted(j["cross_checks"]):
                c = j["cross_checks"][key][str(l)]
                ctrl = ", ".join(f"{x:.3f}" for x in c["median_controls"])
                cells.append(f"{c['median_real']:.4f} [{ctrl}]")
            lines.append(f"| {l} | " + " | ".join(cells) + " |")
        # ---- the control-adjusted table, section 3.5 of the record ---------
        # Each cell is the median real share over the 25 prompts minus the mean
        # over the three rotation seeds of that control's median share, so a
        # positive number means the real dictionary explains more of the state
        # than a randomly rotated copy of the same dictionary does.
        adjusted = [(k, label) for k, label in adjusted_all
                    if k in j["cross_checks"]]
        lines += ["", "### Real minus its own rotation control", "",
                  "Each cell is the median share over the 25 prompts minus the "
                  "mean over the three seeds of the control's median share. A "
                  "positive number means the real dictionary explains more of "
                  "the state than a randomly rotated copy of the same "
                  "dictionary does.", "",
                  "| layer | " + " | ".join(label for _, label in adjusted) + " |",
                  "|---" * (1 + len(adjusted)) + "|"]
        for l in j["probe_layers"]:
            cells = []
            for key, _ in adjusted:
                c = j["cross_checks"][key][str(l)]
                ctrls = c["median_controls"]
                gap = c["median_real"] - sum(ctrls) / len(ctrls)
                cells.append(f"{gap:+.4f}")
            lines.append(f"| {l} | " + " | ".join(cells) + " |")

        if "same_lens_model_effect" in j:
            lines += ["", "### Model effect against instrument effect", "",
                      "The model effect holds the lens fixed and swaps whose "
                      "settled states are decomposed. The instrument effect "
                      "holds the states fixed and swaps the lens. Both are the "
                      "absolute difference of medians over the 25 prompts.", "",
                      "| layer | model effect on the base lens | model effect on "
                      "the twin lens | instrument effect on twin states | "
                      "instrument effect on base states | smallest model effect "
                      "over largest instrument effect |",
                      "|---|---|---|---|---|---|"]
            for l in j["probe_layers"]:
                mb = j["same_lens_model_effect"]["base"][str(l)]
                cells = [f"{mb['model_effect_abs_median_difference']:.4f} "
                         f"(p {mb['perm_p']})"]
                if "twin" in j["same_lens_model_effect"]:
                    mt = j["same_lens_model_effect"]["twin"][str(l)]
                    cells.append(f"{mt['model_effect_abs_median_difference']:.4f} "
                                 f"(p {mt['perm_p']})")
                else:
                    cells.append("not applicable")
                if "same_states_lens_effect" in j:
                    le = j["same_states_lens_effect"]
                    cells.append(f"{le['twin'][str(l)]['lens_effect_abs_median_difference']:.4f}")
                    cells.append(f"{le['base'][str(l)]['lens_effect_abs_median_difference']:.4f}")
                    r = j["model_effect_over_lens_effect"][str(l)]
                    cells.append(f"{r['ratio_smallest_model_over_largest_lens']:.1f} times")
                else:
                    cells += ["not applicable"] * 3
                lines.append(f"| {l} | " + " | ".join(cells) + " |")
            lines.append("")
        lines += ["", "### Lens diagnostics", "",
                  "| layer | " + " | ".join(
                      f"{k} Frobenius norm" for k in sorted(
                          [x for x in j["lens_diagnostics_per_layer"]["0"]
                           if x != "cosine_between_the_two_lenses"]))
                  + " | cosine between the two lenses |",
                  "|---" * (2 + len([x for x in j["lens_diagnostics_per_layer"]["0"]
                                     if x != "cosine_between_the_two_lenses"])) + "|"]
        for l in j["probe_layers"]:
            d = j["lens_diagnostics_per_layer"][str(l)]
            keys = sorted(k for k in d if k != "cosine_between_the_two_lenses")
            cells = [f"{d[k]['frobenius_norm']:.3f}" for k in keys]
            cos = d.get("cosine_between_the_two_lenses")
            lines.append(f"| {l} | " + " | ".join(cells) + " | "
                         + (f"{cos:.4f}" if cos is not None else "not applicable") + " |")
        lines += ["",
                  f"Terminal rescale to the injection size before the per-layer read: "
                  f"{j['terminal_rescale_to_injection_size']}", ""]
    else:
        lines += ["## H18b: the J-space share", "", "Not yet computed.", ""]

    # ---- the same measurement in the Hugging Face frame ---------------------
    # A sensitivity arm, not the registered comparison: the states and the
    # dictionary are read from the Hugging Face model rather than from the
    # TransformerLens conversion, which is the frame the Jacobian matrices were
    # fitted in. Section 3.6 of the record explains why both exist.
    hp = OUT / "exp017_jspace_hfframe.json"
    if hp.exists():
        hj = json.load(open(hp))
        hb = hj["h18b"]
        lines += ["", "## H18b in the Hugging Face frame, a sensitivity arm "
                  "with no verdict weight", "",
                  f"- Reading: **{hb['h18b']}** "
                  f"({hb['n_band_layers_meeting_both']} of the 6 band layers meet "
                  f"both conditions: {hb['band_layers_meeting_both']}).", "",
                  "| layer | twin median share | base median share | absolute "
                  "difference | control spread | permutation p | both conditions "
                  "| band |", "|---|---|---|---|---|---|---|---|"]
        for l in hj["probe_layers"]:
            r = hb["per_layer"][str(l)]
            lines.append(
                f"| {l} | {r['median_twin']:.4f} | {r['median_base']:.4f} "
                f"| {r['abs_median_difference']:.4f} | {r['control_spread']:.4f} "
                f"| {r['perm_p']} | {fmt(r['both_conditions'])} "
                f"| {'yes' if r['in_band'] else 'no'} |")
        # The registered artifact is optional here: without it this section
        # renders the Hugging Face columns alone rather than failing.
        sources = [(j, "registered frame"), (hj, "Hugging Face frame")]
        sources = [(s, label) for s, label in sources if s is not None]
        header = " | ".join(f"{label}, {lens} lens"
                            for s, label in sources for lens in ("base", "twin"))
        lines += ["", "### The same-lens comparison in the two frames", "",
                  "The model effect holds the lens fixed and swaps whose settled "
                  "states are decomposed, so a positive number means the twin's "
                  "states have the higher share. The registered frame is the "
                  "TransformerLens one; the Hugging Face frame is the sensitivity "
                  "arm.", "",
                  f"| layer | {header} |",
                  "|---" * (1 + 2 * len(sources)) + "|"]
        for l in hj["probe_layers"]:
            cells = []
            for source, _ in sources:
                for lens in ("base", "twin"):
                    rows = source.get("same_lens_model_effect", {}).get(lens)
                    if rows is None:
                        cells.append("not applicable")
                        continue
                    r = rows[str(l)]
                    gap = r["median_twin_states"] - r["median_base_states"]
                    cells.append(f"{gap:+.4f} (p {r['perm_p']})")
            lines.append(f"| {l} | " + " | ".join(cells) + " |")
        if "model_effect_over_lens_effect" in hj:
            lines += ["", "### Model effect over instrument effect, Hugging Face "
                      "frame", "",
                      "| layer | smallest model effect | largest instrument "
                      "effect | ratio |", "|---|---|---|---|"]
            for l in hj["probe_layers"]:
                r = hj["model_effect_over_lens_effect"][str(l)]
                lines.append(
                    f"| {l} | {r['smallest_model_effect']:.4f} "
                    f"| {r['largest_lens_effect']:.4f} "
                    f"| {r['ratio_smallest_model_over_largest_lens']:.1f} times |")
        adjusted_hf = [(k, label) for k, label in adjusted_all
                       if k in hj["cross_checks"]]
        lines += ["", "### Real minus its own rotation control, Hugging Face "
                  "frame", "",
                  "| layer | " + " | ".join(label for _, label in adjusted_hf)
                  + " |",
                  "|---" * (1 + len(adjusted_hf)) + "|"]
        for l in hj["probe_layers"]:
            cells = []
            for key, _ in adjusted_hf:
                c = hj["cross_checks"][key][str(l)]
                ctrls = c["median_controls"]
                cells.append(f"{c['median_real'] - sum(ctrls) / len(ctrls):+.4f}")
            lines.append(f"| {l} | " + " | ".join(cells) + " |")
        lines.append("")

    # ---- the frame measurement itself ---------------------------------------
    fp = OUT / "frame_check.json"
    if fp.exists():
        fc = json.load(open(fp))
        lines += ["", "## The two frames, measured", "",
                  "The unembedding the probe used against the model's own output "
                  "matrix. The difference is given relative to the size of the "
                  "Hugging Face matrix, and the common shift is the one vector "
                  "that the two versions of every token direction differ by.", "",
                  "| model | difference relative to the Hugging Face matrix | "
                  "common shift length over mean direction length | fraction of "
                  "the difference left after removing the common shift | per-token "
                  "cosine, median | final normalisation gain, smallest to largest |",
                  "|---|---|---|---|---|---|"]
        for which in sorted(fc["unembedding"]):
            u = fc["unembedding"][which]
            lines.append(
                f"| {which} | {u['difference_relative_to_hugging_face']:.4f} "
                f"| {u['common_shift_over_mean_column_norm']:.4f} "
                f"| {u['fraction_of_the_difference_left_after_removing_the_common_shift']:.4f} "
                f"| {u['per_token_cosine_median']:.4f} "
                f"| {u['final_norm_gain_min']:.4f} to {u['final_norm_gain_max']:.4f} |")
        lines += ["", "The states in the two frames, at the layers measured. The "
                  "mean over the 768 coordinates says whether a state is centred; "
                  "the last column is how much of the state's own length the two "
                  "frames differ by.", "",
                  "| model | layer | mean state length | largest mean over "
                  "coordinates, TransformerLens | largest mean over coordinates, "
                  "Hugging Face | gap length over state length |",
                  "|---|---|---|---|---|---|"]
        for which in sorted(fc["states"]):
            for l in sorted(fc["states"][which], key=int):
                s = fc["states"][which][l]
                lines.append(
                    f"| {which} | {l} | {s['mean_state_norm']:.1f} "
                    f"| {s['max_abs_mean_over_coordinates_transformer_lens']:.2e} "
                    f"| {s['max_abs_mean_over_coordinates_hugging_face']:.4f} "
                    f"| {s['gap_length_over_state_length']:.4f} |")
        lines += ["", f"The share on the first {len(fc['prompt_ids'])} prompts of "
                  "the subset, real dictionaries only, in three combinations: the "
                  "states and dictionary the committed run used, the same states "
                  "against the Hugging Face dictionary, and the Hugging Face "
                  "states against the Hugging Face dictionary.", "",
                  "| layer | combination | twin median | base median | absolute "
                  "difference |", "|---|---|---|---|---|"]
        labels = {"registered": "committed states and dictionary",
                  "hf_dictionary": "committed states, Hugging Face dictionary",
                  "hf_frame": "Hugging Face states and dictionary"}
        for l in sorted(fc["subset_shares"], key=int):
            for key, label in labels.items():
                cell = fc["subset_shares"][l].get(key)
                if cell is None:
                    continue
                lines.append(
                    f"| {l} | {label} | {cell['twin']['median']:.4f} "
                    f"| {cell['base']['median']:.4f} "
                    f"| {cell['absolute_difference_of_medians']:.4f} |")
        lines.append("")

    (OUT / "tables.md").write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nSaved -> output/tables.md")


if __name__ == "__main__":
    main()
